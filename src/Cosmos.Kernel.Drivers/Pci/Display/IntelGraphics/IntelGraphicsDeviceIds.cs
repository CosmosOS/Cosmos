namespace Cosmos.Kernel.Drivers.Pci.Display.IntelGraphics;

/// <summary>
/// The PCI device ids of the integrated GPUs <see cref="IntelGraphicsDriver"/>
/// binds, by platform: Linux's <c>include/drm/intel/pciids.h</c> lists for
/// the Core processors from Sandy Bridge to Raptor Lake. The Atom-class parts
/// (Valley View, Cherry View, Broxton, Gemini Lake, Elkhart Lake, Jasper
/// Lake), the discrete GPUs and the platforms from Meteor Lake on are not
/// here: their display engines differ from the ones this driver reads.
/// </summary>
internal static class IntelGraphicsDeviceIds
{
    /// <summary>Finds the platform a device id belongs to. Any context; allocation-free.</summary>
    /// <param name="deviceId">The function's PCI device id.</param>
    /// <param name="platform">The platform, when the id is in the table.</param>
    /// <returns>False for a device id this driver does not know.</returns>
    internal static bool TryFind(ushort deviceId, out IntelGraphicsPlatform platform)
    {
        IntelGraphicsPlatform? found = deviceId switch
        {
            0x0102 or 0x0106 or 0x010A or 0x0112 or 0x0116 or 0x0122 or 0x0126 => IntelGraphicsPlatform.SandyBridge,

            0x0152 or 0x0156 or 0x015A or 0x0162 or 0x0166 or 0x016A => IntelGraphicsPlatform.IvyBridge,

            0x0402 or 0x0406 or 0x040A or 0x040B or 0x040E or 0x0412 or 0x0416 or 0x041A or 0x041B or 0x041E
                or 0x0422 or 0x0426 or 0x042A or 0x042B or 0x042E or 0x0A02 or 0x0A06 or 0x0A0A or 0x0A0B or 0x0A0E
                or 0x0A12 or 0x0A16 or 0x0A1A or 0x0A1B or 0x0A1E or 0x0A22 or 0x0A26 or 0x0A2A or 0x0A2B or 0x0A2E
                or 0x0C02 or 0x0C06 or 0x0C0A or 0x0C0B or 0x0C0E or 0x0C12 or 0x0C16 or 0x0C1A or 0x0C1B or 0x0C1E
                or 0x0C22 or 0x0C26 or 0x0C2A or 0x0C2B or 0x0C2E or 0x0D02 or 0x0D06 or 0x0D0A or 0x0D0B or 0x0D0E
                or 0x0D12 or 0x0D16 or 0x0D1A or 0x0D1B or 0x0D1E or 0x0D22 or 0x0D26 or 0x0D2A or 0x0D2B or 0x0D2E => IntelGraphicsPlatform.Haswell,

            0x1602 or 0x1606 or 0x160A or 0x160B or 0x160D or 0x160E or 0x1612 or 0x1616 or 0x161A or 0x161B
                or 0x161D or 0x161E or 0x1622 or 0x1626 or 0x162A or 0x162B or 0x162D or 0x162E or 0x1632 or 0x1636
                or 0x163A or 0x163B or 0x163D or 0x163E => IntelGraphicsPlatform.Broadwell,

            0x1902 or 0x1906 or 0x190A or 0x190B or 0x190E or 0x1912 or 0x1913 or 0x1915 or 0x1916 or 0x1917
                or 0x191A or 0x191B or 0x191D or 0x191E or 0x1921 or 0x1923 or 0x1926 or 0x1927 or 0x192A or 0x192B
                or 0x192D or 0x1932 or 0x193A or 0x193B or 0x193D or 0x3E90 or 0x3E91 or 0x3E92 or 0x3E93 or 0x3E94
                or 0x3E96 or 0x3E98 or 0x3E99 or 0x3E9A or 0x3E9B or 0x3E9C or 0x3EA0 or 0x3EA1 or 0x3EA2 or 0x3EA3
                or 0x3EA4 or 0x3EA5 or 0x3EA6 or 0x3EA7 or 0x3EA8 or 0x3EA9 or 0x5902 or 0x5906 or 0x5908 or 0x590A
                or 0x590B or 0x590E or 0x5912 or 0x5913 or 0x5915 or 0x5916 or 0x5917 or 0x591A or 0x591B or 0x591C
                or 0x591D or 0x591E or 0x5921 or 0x5923 or 0x5926 or 0x5927 or 0x593B or 0x87C0 or 0x87CA or 0x9B21
                or 0x9B41 or 0x9BA2 or 0x9BA4 or 0x9BA5 or 0x9BA8 or 0x9BAA or 0x9BAC or 0x9BC2 or 0x9BC4 or 0x9BC5
                or 0x9BC6 or 0x9BC8 or 0x9BCA or 0x9BCC or 0x9BE6 or 0x9BF6 => IntelGraphicsPlatform.Skylake,

            0x8A50 or 0x8A51 or 0x8A52 or 0x8A53 or 0x8A54 or 0x8A56 or 0x8A57 or 0x8A58 or 0x8A59 or 0x8A5A
                or 0x8A5B or 0x8A5C or 0x8A5D or 0x8A70 or 0x8A71 => IntelGraphicsPlatform.IceLake,

            0x4680 or 0x4682 or 0x4688 or 0x468A or 0x468B or 0x4690 or 0x4692 or 0x4693 or 0x4C80 or 0x4C8A
                or 0x4C8B or 0x4C8C or 0x4C90 or 0x4C9A or 0x9A40 or 0x9A49 or 0x9A59 or 0x9A60 or 0x9A68 or 0x9A70
                or 0x9A78 or 0x9AC0 or 0x9AC9 or 0x9AD9 or 0x9AF8 or 0xA780 or 0xA781 or 0xA782 or 0xA783 or 0xA788
                or 0xA789 or 0xA78A or 0xA78B => IntelGraphicsPlatform.TigerLake,

            0x4626 or 0x4628 or 0x462A or 0x46A0 or 0x46A1 or 0x46A2 or 0x46A3 or 0x46A6 or 0x46A8 or 0x46AA
                or 0x46B0 or 0x46B1 or 0x46B2 or 0x46B3 or 0x46C0 or 0x46C1 or 0x46C2 or 0x46C3 or 0x46D0 or 0x46D1
                or 0x46D2 or 0x46D3 or 0x46D4 or 0xA720 or 0xA721 or 0xA7A0 or 0xA7A1 or 0xA7A8 or 0xA7A9 or 0xA7AA
                or 0xA7AB or 0xA7AC or 0xA7AD => IntelGraphicsPlatform.AlderLakeP,

            _ => null,
        };

        platform = found.GetValueOrDefault();
        return found.HasValue;
    }
}
