    /// <summary>
    /// Initialize the early GOP renderer. Called lazily on first PutChar if not called explicitly.
    /// For round displays the usable text area is inset to fit inside the visible circle.
    /// </summary>
    public static void Initialize()
    {
        s_col = 0;
        s_row = 0;
        s_initialized = false;

        if (Limine.Framebuffer.Response == null ||
            Limine.Framebuffer.Response->FramebufferCount == 0)
        {
            return;
        }

        LimineFramebuffer* fb = Limine.Framebuffer.Response->Framebuffers[0];
        int totalCols = (int)(fb->Width / CharW);
        int totalRows = (int)(fb->Height / CharH);

        // Detect "roughly square" screens as round (smartwatch displays).
        // For a circle of diameter D the largest inscribed rectangle with
        // aspect ratio ~3:1 (wide text block) gives a good balance between
        // line width and number of visible lines.  We use the simpler
        // inscribed-square approach:  side = D / sqrt(2) ≈ D * 0.707.
        // Margin on each side = (D - side) / 2 ≈ D * 0.146.
        // We round up to whole character cells.
        bool isRound = fb->Width == fb->Height && fb->Width <= 480;
        if (isRound)
        {
            // Use ~70% of each axis → 15% margin on each side (in pixels).
            int marginPx = (int)(fb->Width * 15 / 100);
            s_marginX = (marginPx + CharW - 1) / CharW; // in character cells
            s_marginY = (marginPx + CharH - 1) / CharH;
        }
        else
        {
            s_marginX = 0;
            s_marginY = 0;
        }

        s_usableCols = totalCols - 2 * s_marginX;
        s_usableRows = totalRows - 2 * s_marginY;

        if (s_usableCols < 1)
        {
            s_usableCols = 1;
        }

        if (s_usableRows < 1)
        {
            s_usableRows = 1;
        }

        s_initialized = true;
    }

    /// <summary>
    /// Write a single character directly to the linear framebuffer.
    /// Handles '\n' (line feed) and '\r' (carriage return).
    /// </summary>
    public static void PutChar(char c)
    {
        if (!Enabled)
        {
            return;
        }

        if (!s_initialized)
        {
            Initialize();
        }

        if (!s_initialized)
        {
            return;
        }

        LimineFramebuffer* fb = Limine.Framebuffer.Response->Framebuffers[0];

        switch (c)
        {
            case '\n':
                s_col = 0;
                s_row++;
                if (s_row >= s_usableRows)
                {
                    ClearUsableRegion(fb);
                    s_row = 0;
                }
                break;
            case '\r':
                s_col = 0;
                break;
            default:
                if (c < 0x20 || c > 0x7E)
                {
                    c = '?';
                }

                DrawGlyph(fb, c, s_col + s_marginX, s_row + s_marginY);
                s_col++;
                if (s_col >= s_usableCols)
                {
                    s_col = 0;
                    s_row++;
                    if (s_row >= s_usableRows)
                    {
                        ClearUsableRegion(fb);
                        s_row = 0;
                    }
                }
                break;
        }
    }

    private static void DrawGlyph(LimineFramebuffer* fb, char c, int col, int row)
    {
        int glyphOffset = (c - 0x20) * CharH;
        int baseX = col * CharW;
        int baseY = row * CharH;
        ulong pitch = fb->Pitch;
        byte* fbAddr = (byte*)fb->Address;

        for (int y = 0; y < CharH; y++)
        {
            byte bits = Font[glyphOffset + y];
            uint* rowPtr = (uint*)(fbAddr + ((ulong)(baseY + y)) * pitch + ((ulong)baseX) * 4);
            for (int x = 0; x < CharW; x++)
            {
                rowPtr[x] = (uint)((bits & (1 << x)) != 0 ? 0x00FFFFFF : 0x00000000);
            }
        }
    }

    /// <summary>
    /// Wipe the usable text region and restart at the top row. This replaces
    /// scrolling on purpose: scrolling has to read the framebuffer back, and
    /// the Limine framebuffer is mapped write-combining, where reads are
    /// uncached (~100ms per full-frame read under KVM or on real hardware —
    /// that made every boot-log line cost ~100ms once the screen filled).
    /// Clearing is write-only, and WC writes stream fast.
    /// </summary>
    private static void ClearUsableRegion(LimineFramebuffer* fb)
    {
        ulong pitch = fb->Pitch;
        byte* addr = (byte*)fb->Address;

        ulong topPx = (ulong)(s_marginY * CharH);
        ulong usableHeightPx = (ulong)(s_usableRows * CharH);

        ulong* clear = (ulong*)(addr + pitch * topPx);
        ulong count = pitch * usableHeightPx / 8;
        for (ulong i = 0; i < count; i++)
        {
            clear[i] = 0;
        }
    }
